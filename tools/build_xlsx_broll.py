WIDTHS = [5, 13, 32, 15, 17, 9, 15, 14, 46, 8, 22]


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "Bロール"
    ws.sheet_view.showGridLines = False

    ws["A1"] = "BROOKLYN MUSEUM ／ 向島工房　動画制作"
    ws["A1"].font = Font(name=JP, size=9, color=MUTED)
    ws["A2"] = "Bロール参考ショット集"
    ws["A2"].font = Font(name=JP, size=18, bold=True, color=INK)
    ws["A3"] = "編集の呼吸を作るための素材カット。絵コンテに載っているカットは一つも入っていません。"
    ws["A3"].font = Font(name=JP, size=10, color=MUTED)

    r = 5
    for t, c, b in [
        ("02 ショットリスト（Aロール）とのちがい", INK, True),
        ("　02 ＝ 被写体の動作や言葉が意味を作るカット。一つ欠けるとその動画が成立しない。撮影当日に必ず消化する。", MUTED, False),
        ("　04 ＝ それ自体は何も語らないが、編集の呼吸を作る素材。無くても動画は成立するが、無いとカットが繋がらない。", MUTED, False),
        ("　場面や工程では分けていません。撮影の役割で分けています。同じカットが両方に載ることはありません。", ACCENT, False),
    ]:
        ws.cell(row=r, column=1, value=t).font = Font(name=JP, size=9, bold=b, color=c)
        r += 1

    r += 1
    last = 12 + len(SHOTS) - 1
    ws.cell(row=r, column=1, value="ショット数").font = Font(name=JP, size=9, color=MUTED)
    ws.cell(row=r, column=2, value=f"=COUNTA(C12:C{last})").font = Font(name=JP, size=11, bold=True, color=INK)
    ws.cell(row=r, column=3, value="撮影済").font = Font(name=JP, size=9, color=MUTED)
    ws.cell(row=r, column=4, value=f"=COUNTA(J12:J{last})").font = Font(name=JP, size=11, bold=True, color=ACCENT)
    ws.cell(row=r, column=5, value="うち音だけの素材").font = Font(name=JP, size=9, color=MUTED)
    ws.cell(row=r, column=6, value=f'=COUNTIF(B12:B{last},"音の素材（映像は使わない）")').font = Font(name=JP, size=11, bold=True, color=MUTED)

    hr = 11
    for i, (h, w) in enumerate(zip(HEADERS, WIDTHS), start=1):
        c = ws.cell(row=hr, column=i, value=h)
        c.font = Font(name=JP, size=9, bold=True, color=MUTED)
        c.fill = PatternFill("solid", fgColor=HEAD_FILL)
        c.alignment = Alignment(vertical="center", wrap_text=True)
        c.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[hr].height = 26

    prev = None
    for n, s in enumerate(SHOTS, start=1):
        row = hr + n
        for i, v in enumerate([n] + list(s) + ["", ""], start=1):
            c = ws.cell(row=row, column=i, value=v)
            c.font = Font(name=JP, size=9, color=INK if i == 3 else MUTED, bold=(i == 3))
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = BORDER
            if i == 2 and s[0] != prev:
                c.fill = PatternFill("solid", fgColor=GRP_FILL)
                c.font = Font(name=JP, size=9, bold=True, color=ACCENT)
            if i in (10, 11):
                c.fill = PatternFill("solid", fgColor=INPUT_FILL)
        prev = s[0]
        ws.row_dimensions[row].height = 44

    ws.freeze_panes = "A12"
    ws.auto_filter.ref = f"A{hr}:K{hr + len(SHOTS)}"
    out = os.path.join(ROOT, "pdf", "04_Bロール参考ショット集.xlsx")
    wb.save(out)
    print(out, f"／ {len(SHOTS)}ショット")


if __name__ == "__main__":
    main()
