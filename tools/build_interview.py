def main():
    out = build()
    for w in NG:
        assert w not in out, "使わない言葉が入っている: " + w
    for w in DUP:
        assert w not in out, "香盤表と被る書き方が入っている: " + w
    eng = sum(1 for q, _, _ in PEOPLE[-1]["qs"] if "eng" in q)
    assert eng == len(PEOPLE[-1]["qs"]) - 1, "テロップに出す質問は日英併記にする"
    path = os.path.join(ROOT, "temoto.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(out)
    print(path, len(out), "バイト　技術",
          sum(len(t[3]) for t in TECH), "項　質問", sum(len(p["qs"]) for p in PEOPLE), "問")


if __name__ == "__main__":
    main()
