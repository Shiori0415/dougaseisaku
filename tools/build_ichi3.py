    for d in (A, B, C):
        pages.append(vpage(d["no"], d["jp"], d["en"], d["meta_len"], d["meta_target"], d["ref"],
                           d["plan"], d["says"], d["telop_jp"], d["telop_en"], d["extra"],
                           d["rows"], d["pn"], d["total"]))
    out = os.path.join(ROOT, "pdf", "ichi3.html")
    build(pages, out)
    h = open(out, encoding="utf-8").read()
    h = h.replace("</style>", EXTRA + "\n</style>")
    open(out, "w", encoding="utf-8").write(h)
    print(out, len(h), "バイト")


