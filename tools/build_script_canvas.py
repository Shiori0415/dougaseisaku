def loc_cell(pg, si):
    """ロケ地の欄。場所が前のシーンと同じときは「同じ」"""
    place, query, _, _ = SPOT[pg["no"]][si]
    link = ""
    if query:
        link = (f'<div style="margin-top: 5px; font-size: 14.5px">'
                f'<a href="{_maps(query)}" target="_blank" rel="noopener" style="color: {GOLD}; text-decoration: underline">地図</a>'
                f'　<a href="{_earth(query)}" target="_blank" rel="noopener" style="color: {GOLD}; text-decoration: underline">アース</a>'
                f'　<span style="color: {FAINT}">{esc(query)}</span></div>')
    if place == "同じ":
        return f'<span style="color: {MUTED}">同じ</span>{link}'
    head = f'<div style="font-weight: 700">{place}</div>'
    if si == 1 and len(LOC[pg["no"]].get("spots") or []) > 2:
        alts = [n for n, _ in LOC[pg["no"]]["spots"]][1:]
        if alts:
            head += (f'<div style="margin-top: 7px; font-size: 14.5px; color: {MUTED}">'
                     f'ほかの候補：{"／".join(alts)}</div>')
    return head + link


def cam_cell(pg, si, cam):
    """時間とカメラの欄。時刻を先に出し、そのシーンに当てた撮り方を下に足す"""
    _, _, day, when = SPOT[pg["no"]][si]
    head = (f'<div style="font-size: 18px; font-weight: 700; color: {GOLD}; margin-bottom: 8px">'
            f'{esc(day)}　{esc(when)}</div>')
    light = ""
    if si == 1:
        light = (f'<div style="margin-top: 10px; font-size: 16px; color: {MUTED}">'
                 f'<b>光</b>　{LOC[pg["no"]]["light"]}</div>')
    hows = [t for k, t in zip(HOW_AT[pg["no"]], LOC[pg["no"]]["how"]) if k == si]
    how = "".join(
        f'<div style="display: flex; gap: 9px; margin-top: 8px; font-size: 16px; color: {MUTED}">'
        f'<div style="flex: 0 0 14px; color: {GOLD}">・</div><div>{t}</div></div>' for t in hows)
    return head + f'<div>{cam}</div>' + light + how


def scene_rows(pg):
    out = []
    td = f'padding: 17px 16px; border-bottom: 1px solid {LINE}; vertical-align: top'
    body = f'font-size: 18px; line-height: 1.8; color: {INK}'
    for si, (nm, tm, shots) in enumerate(pg["rows"], 1):
        cuts = [sh for sh in shots if sh[1] != "―"]
        cam, snd, tel = D[pg["no"]].get(si, ("", "", ""))
        out.append(f'''<tr>
      <td style="{td}; padding-left: 0">
        <div style="font-size: 21px; font-weight: 700; color: {INK}">{esc(nm)}</div>
        <div style="font-size: 15px; color: {MUTED}; margin-top: 6px">{esc(re.sub(r"　｜.*", "", tm))}</div>
        <div style="font-size: 15px; color: {FAINT}; margin-top: 4px">{len(cuts)}カット</div>
      </td>
      <td style="{td}"><div style="{body}">{loc_cell(pg, si)}</div></td>
      <td style="{td}"><div style="{body}">{cam_cell(pg, si, cam)}</div></td>
      <td style="{td}"><div style="{body}">{snd}</div></td>
      <td style="{td}; padding-right: 0"><div style="{body}">{tel}</div></td>
    </tr>''')
    return "\n".join(out)


