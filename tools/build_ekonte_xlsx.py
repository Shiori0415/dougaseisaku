def row(vals, *, font=None, align=None, fill=None, height=None, merge=None, border=False):
    r = ws.max_row + 1 if ws.max_row > 1 or ws["A1"].value else 1
    for i, v in enumerate(vals, start=1):
        c = ws.cell(row=r, column=i, value=v)
        c.font = font or Font(name=F, size=10, color=INK)
        c.alignment = align or Alignment(vertical="top", wrap_text=True)
        if fill:
            c.fill = PatternFill("solid", fgColor=fill)
        if border:
            c.border = box
    if merge:
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=merge)
    if height:
        ws.row_dimensions[r].height = height
    return r

def blank(h=6):
    r = ws.max_row + 1
    ws.row_dimensions[r].height = h
    ws.cell(row=r, column=1, value=None)

