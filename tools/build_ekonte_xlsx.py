def video(no, title, en, spec, target, plan, ref, refnote, scenes, total):
    row([f"{no}　{title}"], font=Font(name=F, size=16, bold=True, color=INK), height=26, merge=NC)
    row([en], font=Font(name=F, size=11, color=ACC), height=18, merge=NC)
    row([spec], font=Font(name=F, size=10, bold=True, color=INK), height=17, merge=NC)
    row([target], font=Font(name=F, size=9, color="555555"), height=17, merge=NC)
    blank(4)
    row([plan], font=Font(name=F, size=9.5, color=INK),
        height=max(30, 13 * (len(plan) // 78 + 1)), merge=NC, fill=SOFT)
    if ref:
        row([ref], font=Font(name=F, size=9, bold=True, color=ACC), height=17, merge=NC)
    if refnote:
        row([refnote], font=Font(name=F, size=8.5, color="555555"),
            height=max(26, 11 * (len(refnote) // 88 + 1)), merge=NC)
    blank(10)

    for head, shots in scenes:
        row([head], font=Font(name=F, size=10, bold=True, color=INK),
            height=20, merge=NC, fill=BAND)
        r = ws.max_row + 1
        for i, s in enumerate(shots, start=1):
            c = ws.cell(row=r, column=i, value=s)
            c.font = Font(name=F, size=9, color=INK)
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = box
        longest = max(len(s) for s in shots)
        ws.row_dimensions[r].height = max(46, 12 * (longest // 24 + 1))
        blank(4)

    row([f"BROOKLYN MUSEUM ／ 向島工房 動画制作　　{total}"],
        font=Font(name=F, size=9, color="777777"), height=18, merge=NC)
    blank(26)


